export type IconName = keyof typeof ICONS;

type Props = {
  name: IconName;
  size?: number;
  color?: string;
  className?: string;
};

export default function PixelIcon({ name, size = 24, color = 'currentColor', className = '' }: Props) {
  const rows = ICONS[name];

  return (
    <svg
      viewBox="0 0 12 12"
      width={size}
      height={size}
      className={className}
      shapeRendering="crispEdges"
      role="img"
      aria-label={name}
    >
      {rows.map((row, y) =>
        row.split('').map((ch, x) =>
          ch === '#' ? (
            <rect key={`${x}-${y}`} x={x} y={y} width="1.02" height="1.02" fill={color} />
          ) : null,
        ),
      )}
    </svg>
  );
}
